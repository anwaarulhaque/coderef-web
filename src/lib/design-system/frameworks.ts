// Framework exports (Pro): the same tokens as Tailwind v3/v4, a shadcn/ui theme, W3C design tokens (DTCG) for token
// pipelines, and a Tokens Studio file that becomes Figma variables with Light/Dark modes.
import { cssVar } from "./css.ts";
import { slugify } from "./parse.ts";
import { ROLES, type DesignSystem, type Role, type ThemeName } from "./types.ts";

const header = (ds: DesignSystem, what: string) => `${ds.name} — ${what}. Generated by CodeRef from ${ds.id} (source ${ds.version}).`;
const kebab = (r: Role) => r.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

/** tailwind.config.js (v3): colours point at the CSS variables in styles.css, so both themes work. */
export function tailwindV3(ds: DesignSystem): string {
  const colors = Object.fromEntries(ROLES.map((r) => [kebab(r), `var(${cssVar(r)})`]));
  const theme = {
    colors,
    fontFamily: { display: ["var(--ds-font-display)"], sans: ["var(--ds-font-body)"], mono: ["var(--ds-font-mono)"] },
    borderRadius: Object.fromEntries(ds.radius.value.map((r) => [slugify(r.name), r.value])),
    spacing: Object.fromEntries(ds.spacing.value.map((s) => [`ds-${slugify(s.name)}`, s.value])),
    boxShadow: Object.fromEntries(ds.shadows.value.map((s) => [slugify(s.name), s.value])),
    fontSize: Object.fromEntries(ds.typeScale.value.map((t) => [slugify(t.name), [t.fontSize, { ...(t.lineHeight && { lineHeight: t.lineHeight }), ...(t.letterSpacing && { letterSpacing: t.letterSpacing }), ...(t.fontWeight && { fontWeight: t.fontWeight }) }]])),
    screens: Object.fromEntries(ds.breakpoints.value.map((b, i) => [["sm", "md", "lg", "xl", "2xl", "3xl", "4xl"][i] ?? `bp${i}`, b])),
  };
  return `// ${header(ds, "Tailwind CSS v3 config")}
// Import styles.css (from the package) once in your global CSS so the --ds-* variables exist.
// Dark mode: add data-theme="dark" to <html>.
/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: ["selector", '[data-theme="dark"]'],
  theme: {
    extend: ${JSON.stringify(theme, null, 2).replace(/\n/g, "\n    ")},
  },
};
`;
}

/** tailwind.css (v4): an @theme block plus the light/dark values. */
export function tailwindV4(ds: DesignSystem): string {
  const vars = (t: ThemeName) => ROLES.map((r) => `  ${cssVar(r)}: ${ds.themes[t][r].value};`).join("\n");
  return `/* ${header(ds, "Tailwind CSS v4 theme")} */
@import "tailwindcss";
@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));

:root {
${vars("light")}
}
[data-theme="dark"] {
${vars("dark")}
}

@theme inline {
${ROLES.map((r) => `  --color-${kebab(r)}: var(${cssVar(r)});`).join("\n")}
  --font-display: ${ds.fonts.display.value};
  --font-sans: ${ds.fonts.body.value};
  --font-mono: ${ds.fonts.mono.value};
${ds.radius.value.map((r) => `  --radius-${slugify(r.name)}: ${r.value};`).join("\n")}
${ds.shadows.value.map((s) => `  --shadow-${slugify(s.name)}: ${s.value};`).join("\n")}
${ds.typeScale.value.map((t) => `  --text-${slugify(t.name)}: ${t.fontSize};`).join("\n")}
${ds.breakpoints.value.map((b, i) => `  --breakpoint-${["sm", "md", "lg", "xl", "2xl", "3xl", "4xl"][i] ?? `bp${i}`}: ${b};`).join("\n")}
}
`;
}

/** shadcn/ui theme: paste over the :root and .dark blocks in globals.css. */
export function shadcnTheme(ds: DesignSystem): string {
  const block = (t: ThemeName) => {
    const v = ds.themes[t];
    const map: [string, string][] = [
      ["background", v.background.value], ["foreground", v.foreground.value],
      ["card", v.surface.value], ["card-foreground", v.foreground.value],
      ["popover", v.surface.value], ["popover-foreground", v.foreground.value],
      ["primary", v.primary.value], ["primary-foreground", v.onPrimary.value],
      ["secondary", v.secondary.value], ["secondary-foreground", v.foreground.value],
      ["muted", v.surface.value], ["muted-foreground", v.muted.value],
      ["accent", v.accent.value], ["accent-foreground", v.foreground.value],
      ["destructive", t === "dark" ? "#f87171" : "#dc2626"],
      ["border", v.border.value], ["input", v.border.value], ["ring", v.primary.value],
    ];
    return map.map(([k, val]) => `  --${k}: ${val};`).join("\n");
  };
  const radius = ds.radius.value.find((r) => r.name === "md")?.value ?? ds.radius.value[Math.floor(ds.radius.value.length / 2)]?.value ?? "0.5rem";
  return `/* ${header(ds, "shadcn/ui theme")}
   Replace the :root and .dark blocks in your globals.css. "destructive" is a CodeRef default. */
:root {
  --radius: ${radius};
${block("light")}
}

.dark {
${block("dark")}
}
`;
}

/** W3C Design Tokens (DTCG) JSON, with each token's provenance in $extensions. */
export function dtcgTokens(ds: DesignSystem): string {
  const prov = (from: string) => ({ "xyz.coderef": { provenance: from } });
  const color = (t: ThemeName) => Object.fromEntries(ROLES.map((r) => [kebab(r), { $type: "color", $value: ds.themes[t][r].value, $extensions: prov(ds.themes[t][r].from) }]));
  const dim = (list: { name: string; value: string }[], from: string) => Object.fromEntries(list.map((x) => [slugify(x.name), { $type: "dimension", $value: x.value, $extensions: prov(from) }]));
  const tokens = {
    $description: header(ds, "W3C design tokens"),
    color: { light: color("light"), dark: color("dark"), palette: Object.fromEntries(ds.palette.value.map((p) => [slugify(p.name), { $type: "color", $value: p.hex, $extensions: prov(ds.palette.from) }])) },
    font: {
      display: { $type: "fontFamily", $value: ds.fonts.display.value, $extensions: prov(ds.fonts.display.from) },
      body: { $type: "fontFamily", $value: ds.fonts.body.value, $extensions: prov(ds.fonts.body.from) },
      mono: { $type: "fontFamily", $value: ds.fonts.mono.value, $extensions: prov(ds.fonts.mono.from) },
    },
    typography: Object.fromEntries(
      ds.typeScale.value.map((t) => [slugify(t.name), { $type: "typography", $value: { fontFamily: t.fontFamily ?? ds.fonts.body.value, fontSize: t.fontSize, ...(t.fontWeight && { fontWeight: t.fontWeight }), ...(t.lineHeight && { lineHeight: t.lineHeight }), ...(t.letterSpacing && { letterSpacing: t.letterSpacing }) }, $extensions: prov(ds.typeScale.from) }]),
    ),
    radius: dim(ds.radius.value, ds.radius.from),
    spacing: dim(ds.spacing.value, ds.spacing.from),
    shadow: Object.fromEntries(
      ds.shadows.value.flatMap((s) => {
        const layers = parseShadow(s.value);
        if (!layers) return [];
        const v = layers.map((l) => ({ color: l.color, offsetX: l.x, offsetY: l.y, blur: l.blur, spread: l.spread, ...(l.inset && { inset: true }) }));
        return [[slugify(s.name), { $type: "shadow", $value: v.length === 1 ? v[0] : v, $extensions: prov(ds.shadows.from) }]];
      }),
    ),
  };
  return JSON.stringify(tokens, null, 2) + "\n";
}

export type ShadowLayer = { x: string; y: string; blur: string; spread: string; color: string; inset: boolean };

/** Splits on commas that aren't inside parentheses (rgba(…) has its own). */
const splitTop = (v: string) => {
  const out: string[] = [];
  let depth = 0;
  let cur = "";
  for (const ch of v) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      out.push(cur);
      cur = "";
    } else cur += ch;
  }
  return [...out, cur].map((x) => x.trim()).filter(Boolean);
};

/** CSS box-shadow → structured layers (x, y, blur, spread, colour). Null when it can't be read reliably. */
export function parseShadow(css: string): ShadowLayer[] | null {
  if (!css || css.trim() === "none") return null;
  const layers: ShadowLayer[] = [];
  for (const part of splitTop(css)) {
    const color = part.match(/rgba?\([^)]*\)|hsla?\([^)]*\)|#[0-9a-f]{3,8}\b/i)?.[0];
    const rest = part.replace(color ?? "", " ");
    const inset = /\binset\b/i.test(rest);
    const lengths = rest.replace(/\binset\b/i, " ").trim().split(/\s+/).filter(Boolean);
    if (lengths.length < 2 || lengths.length > 4 || !lengths.every((l) => /^-?\d*\.?\d+(px|rem|em)?$/.test(l))) return null;
    const px = (l: string | undefined) => (!l ? "0px" : /[a-z]$/.test(l) ? l : `${l}px`);
    layers.push({ x: px(lengths[0]), y: px(lengths[1]), blur: px(lengths[2]), spread: px(lengths[3]), color: color ?? "rgba(0, 0, 0, 0.25)", inset });
  }
  return layers.length ? layers : null;
}

const GENERIC = /^(ui-sans-serif|ui-serif|ui-monospace|system-ui|-apple-system|blinkmacsystemfont|sans-serif|serif|monospace|cursive|fantasy|inherit|initial)$/i;
/** Figma needs one installed family, not a CSS stack: the first concrete name, else Inter (Figma's default). */
export function figmaFamily(stack: string, mono = false): string {
  const first = stack.split(",").map((f) => f.trim().replace(/^["']|["']$/g, "")).find((f) => f && !GENERIC.test(f));
  return first || (mono ? "Roboto Mono" : "Inter");
}

/** Figma has no unitless line height: 1.4 becomes 140%. */
const figmaLineHeight = (v: string | undefined) => (!v ? undefined : /^\d*\.?\d+$/.test(v) ? `${Math.round(parseFloat(v) * 100)}%` : v);

/**
 * figma-tokens.json for the Tokens Studio plugin: a core set (palette, radius, spacing, type, shadows) plus light and
 * dark sets with the same semantic names, and $themes so "Export to Figma" makes a "Mode" variable collection with
 * Light and Dark modes (and a "Core" collection). Uses Tokens Studio's own token types.
 */
export function tokensStudio(ds: DesignSystem): string {
  const t = (type: string, value: unknown, description?: string) => ({ $type: type, $value: value, ...(description && { $description: description }) });
  const semantic = (theme: ThemeName) => ({ color: Object.fromEntries(ROLES.map((r) => [kebab(r), t("color", ds.themes[theme][r].value, ds.themes[theme][r].from === "source" ? undefined : `${ds.themes[theme][r].from} value`)])) });
  const families = { display: figmaFamily(ds.fonts.display.value), body: figmaFamily(ds.fonts.body.value), mono: figmaFamily(ds.fonts.mono.value, true) };
  const core = {
    palette: Object.fromEntries(ds.palette.value.map((p) => [slugify(p.name), t("color", p.hex)])),
    radius: Object.fromEntries(ds.radius.value.map((r) => [slugify(r.name), t("borderRadius", r.value)])),
    spacing: Object.fromEntries(ds.spacing.value.map((x) => [slugify(x.name), t("spacing", x.value)])),
    font: { family: Object.fromEntries(Object.entries(families).map(([k, v]) => [k, t("fontFamilies", v)])) },
    typography: Object.fromEntries(
      ds.typeScale.value.map((s) => {
        const family = s.fontFamily ? figmaFamily(s.fontFamily) : families.body;
        const value = { fontFamily: family, fontSize: s.fontSize, ...(s.fontWeight && { fontWeight: s.fontWeight }), ...(figmaLineHeight(s.lineHeight) && { lineHeight: figmaLineHeight(s.lineHeight) }), ...(s.letterSpacing && { letterSpacing: s.letterSpacing }) };
        return [slugify(s.name), t("typography", value)];
      }),
    ),
    shadow: Object.fromEntries(
      ds.shadows.value.flatMap((s) => {
        const layers = parseShadow(s.value);
        if (!layers) return [];
        const v = layers.map((l) => ({ x: l.x, y: l.y, blur: l.blur, spread: l.spread, color: l.color, type: l.inset ? "innerShadow" : "dropShadow" }));
        return [[slugify(s.name), t("boxShadow", v.length === 1 ? v[0] : v)]];
      }),
    ),
  };
  const file = {
    core,
    light: semantic("light"),
    dark: semantic("dark"),
    $themes: [
      { id: "core", name: "Default", group: "Core", selectedTokenSets: { core: "enabled" } },
      { id: "light", name: "Light", group: "Mode", selectedTokenSets: { core: "source", light: "enabled" } },
      { id: "dark", name: "Dark", group: "Mode", selectedTokenSets: { core: "source", dark: "enabled" } },
    ],
    $metadata: { tokenSetOrder: ["core", "light", "dark"] },
  };
  return JSON.stringify(file, null, 2) + "\n";
}

