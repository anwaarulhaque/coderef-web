// CSS for the generated package: custom properties for both themes (styles.css) plus the layout used by the previews.
import { slugify } from "./parse.ts";
import { ROLES, type ComponentSpec, type DesignSystem, type Role, type ThemeName } from "./types.ts";

export const cssVar = (role: Role) => `--ds-${role.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`;
const themeVars = (ds: DesignSystem, t: ThemeName) => ROLES.map((r) => `${cssVar(r)}:${ds.themes[t][r].value}`).join(";");

export const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Radius / padding that a source component defines, with a fallback from the token scale. */
export function componentStyle(ds: DesignSystem, kind: "button" | "input" | "card") {
  const match: Record<typeof kind, RegExp[]> = {
    button: [/button.*primary|primary.*button|^button$/, /button|btn|cta/],
    input: [/input|field|text-?box/],
    card: [/^card$|card.*(default|feature|light)|^card/, /card|panel/],
  };
  let spec: ComponentSpec | undefined;
  for (const re of match[kind]) spec ??= ds.components.find((c) => re.test(c.name.toLowerCase()) && !/pressed|hover|focus|disabled/.test(c.name));
  const scale = ds.radius.value;
  const byName = (n: string) => scale.find((r) => r.name === n)?.value;
  const mid = scale[Math.floor(scale.length / 2)]?.value ?? "8px";
  const fallbackRadius = kind === "card" ? byName("lg") ?? scale[scale.length - 1]?.value ?? mid : kind === "input" ? byName("sm") ?? byName("md") ?? mid : byName("md") ?? mid;
  return {
    radius: spec?.rounded ?? fallbackRadius,
    padding: spec?.padding ?? (kind === "button" ? "10px 18px" : kind === "input" ? "10px 12px" : "24px"),
    fromSource: !!spec,
  };
}

/** Theme-independent tokens (fonts, radius, spacing, shadows). */
function sharedVars(ds: DesignSystem): string {
  const v = [
    `--ds-font-display:${ds.fonts.display.value}`,
    `--ds-font-body:${ds.fonts.body.value}`,
    `--ds-font-mono:${ds.fonts.mono.value}`,
    ...ds.radius.value.map((r) => `--ds-radius-${slugify(r.name)}:${r.value}`),
    ...ds.spacing.value.map((s) => `--ds-space-${slugify(s.name)}:${s.value}`),
    ...ds.shadows.value.map((s) => `--ds-shadow-${slugify(s.name)}:${s.value}`),
  ];
  return v.join(";");
}

/** The tokens as CSS custom properties: light by default, dark under [data-theme="dark"] or the OS preference. */
export function tokensCss(ds: DesignSystem): string {
  const light = themeVars(ds, "light");
  const dark = themeVars(ds, "dark");
  return `/* ${esc(ds.name)} — design tokens. Generated by CodeRef from ${esc(ds.id)} (source ${ds.version}). */
:root,[data-theme="light"]{color-scheme:light;${light};${sharedVars(ds)}}
[data-theme="dark"]{color-scheme:dark;${dark}}
@media (prefers-color-scheme:dark){:root:not([data-theme]){color-scheme:dark;${dark}}}
`;
}

const btn = (ds: DesignSystem) => componentStyle(ds, "button");
const inp = (ds: DesignSystem) => componentStyle(ds, "input");
const card = (ds: DesignSystem) => componentStyle(ds, "card");

