export function getFontPairById(id?: string): FontPair {
  if (!id) return DEFAULT_FONT_PAIR;
  const match = FONT_PAIRS.find((f) => f.id.toLowerCase() === id.toLowerCase());
  return match ?? DEFAULT_FONT_PAIR;
}
